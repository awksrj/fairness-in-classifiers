# ============================================================
# unaware_no_proxies_lr_pipeline.py
# ============================================================

import os
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score


# ============================================================
# CONFIGURATION
# ============================================================

RANDOM_SEED = 42

# ------------------------------------------------------------
# Files
#
# IMPORTANT:
# Use the SAME original dataset generated by the aware experiment.
# ------------------------------------------------------------

DATA_CSV_PATH = "fairness_through_unawareness\\1-aware_experiment\\2-original_data.csv"

PREDICTIONS_CSV_PATH = (
    "fairness_through_unawareness\\3-unaware_noproxies_experiment\\3-unaware_no_proxies_predictions.csv"
)

COEFFICIENTS_CSV_PATH = (
    "fairness_through_unawareness\\3-unaware_noproxies_experiment\\4-unaware_no_proxies_coefficients.csv"
)

PLOT_PNG_PATH = (
    "fairness_through_unawareness\\3-unaware_noproxies_experiment\\5-unaware_no_proxies_predictions.png"
)


# ------------------------------------------------------------
# Dataset
# ------------------------------------------------------------

TEST_SIZE = 0.25


# ------------------------------------------------------------
# Classification
# ------------------------------------------------------------

THRESHOLD = 0.50

NEAR_THRESHOLD_LOW = 0.40
NEAR_THRESHOLD_HIGH = 0.60


# ------------------------------------------------------------
# Logistic regression
# ------------------------------------------------------------

MAX_ITER = 1000


# ------------------------------------------------------------
# Feature columns
#
# Gender, Hobby, and Major are all removed.
# ------------------------------------------------------------

NUMERIC_FEATURES = [
    "SAT",
    "GPA"
]

FEATURE_COLUMNS = NUMERIC_FEATURES

TARGET_COLUMN = "Admission"

PROTECTED_COLUMN = "Gender"


# ============================================================
# CREATE OUTPUT DIRECTORY
# ============================================================

os.makedirs(
    os.path.dirname(PREDICTIONS_CSV_PATH),
    exist_ok=True
)


# ============================================================
# LOAD ORIGINAL DATA
# ============================================================

df = pd.read_csv(
    DATA_CSV_PATH
)


# ============================================================
# DISPLAY ORIGINAL DATA DISTRIBUTION
# ============================================================

print("=" * 70)
print("ORIGINAL DATA")
print("=" * 70)

print(
    f"Rows: {len(df)}"
)

print()

print("Gender counts:")

print(
    df["Gender"]
    .value_counts()
)

print()

print("Actual admission rates:")

print(
    df.groupby("Gender")["Admission"]
    .mean()
)


actual_rates = (
    df.groupby("Gender")["Admission"]
    .mean()
)

actual_dbr = (
    actual_rates["Male"]
    - actual_rates["Female"]
)

print()

print(
    f"Difference in base rates "
    f"(Male - Female): "
    f"{actual_dbr:.4f}"
)


# ============================================================
# TRAIN / TEST SPLIT
#
# Same RANDOM_SEED and TEST_SIZE as previous experiments.
# ============================================================

train_indices, test_indices = (
    train_test_split(
        df.index,
        test_size=TEST_SIZE,
        random_state=RANDOM_SEED,
        stratify=df[TARGET_COLUMN]
    )
)


train_df = df.loc[
    train_indices
].copy()

test_df = df.loc[
    test_indices
].copy()


# ============================================================
# MODEL INPUTS
#
# Only SAT and GPA are used.
#
# Removed:
# - Gender
# - Hobby
# - Major
# ============================================================

X_train = train_df[
    FEATURE_COLUMNS
]

X_test = test_df[
    FEATURE_COLUMNS
]

y_train = train_df[
    TARGET_COLUMN
]

y_test = test_df[
    TARGET_COLUMN
]


# ============================================================
# PREPROCESSING
# ============================================================

preprocessor = ColumnTransformer(
    transformers=[
        (
            "numeric",
            StandardScaler(),
            NUMERIC_FEATURES
        )
    ]
)


# ============================================================
# UNAWARE LOGISTIC REGRESSION WITHOUT PROXIES
#
# Inputs:
# SAT + GPA
# ============================================================

model = Pipeline(
    steps=[
        (
            "preprocessor",
            preprocessor
        ),
        (
            "classifier",
            LogisticRegression(
                max_iter=MAX_ITER,
                random_state=RANDOM_SEED
            )
        )
    ]
)


# ============================================================
# TRAIN MODEL
# ============================================================

model.fit(
    X_train,
    y_train
)


# ============================================================
# PREDICT
# ============================================================

probabilities = (
    model.predict_proba(
        X_test
    )[:, 1]
)


predictions = (
    probabilities >= THRESHOLD
).astype(int)


# ============================================================
# CREATE TEST RESULTS DATAFRAME
#
# Keep Gender/Hobby/Major only for later analysis.
# The model did NOT use them.
# ============================================================

results = test_df[
    [
        "ID",
        "Gender",
        "SAT",
        "GPA",
        "Hobby",
        "Major"
    ]
].copy()


results["Actual_Admission"] = (
    y_test.values
)

results["Predicted_Probability"] = (
    probabilities
)

results["Predicted_Admission"] = (
    predictions
)

results["Near_Threshold"] = (
    results["Predicted_Probability"]
    .between(
        NEAR_THRESHOLD_LOW,
        NEAR_THRESHOLD_HIGH
    )
)


results.to_csv(
    PREDICTIONS_CSV_PATH,
    index=False
)


# ============================================================
# ACCURACY
# ============================================================

accuracy = accuracy_score(
    y_test,
    predictions
)


# ============================================================
# POSITIVE PREDICTION RATES
# ============================================================

male_results = results[
    results["Gender"] == "Male"
]

female_results = results[
    results["Gender"] == "Female"
]


male_positive_rate = (
    male_results[
        "Predicted_Admission"
    ]
    .mean()
)


female_positive_rate = (
    female_results[
        "Predicted_Admission"
    ]
    .mean()
)


# ============================================================
# DISPARATE IMPACT DIFFERENCE
#
# DI =
# P(predicted positive | Male)
# -
# P(predicted positive | Female)
#
# Gender is used ONLY for evaluation.
# ============================================================

disparate_impact = (
    male_positive_rate
    - female_positive_rate
)


# ============================================================
# NEAR-THRESHOLD ANALYSIS
# ============================================================

male_near = male_results[
    male_results[
        "Near_Threshold"
    ]
]


female_near = female_results[
    female_results[
        "Near_Threshold"
    ]
]


# ============================================================
# OUTPUT METRICS
# ============================================================

print()

print("=" * 70)
print("UNAWARE LOGISTIC REGRESSION - NO PROXIES")
print("=" * 70)


print(
    f"Features: "
    f"{', '.join(FEATURE_COLUMNS)}"
)

print(
    "Removed attributes: Gender, Hobby, Major"
)

print()


print(
    f"Accuracy: "
    f"{accuracy:.4f}"
)

print()


print(
    f"Male positive prediction rate: "
    f"{male_positive_rate:.4f}"
)


print(
    f"Female positive prediction rate: "
    f"{female_positive_rate:.4f}"
)

print()


print(
    f"Disparate impact "
    f"(Male - Female): "
    f"{disparate_impact:.4f}"
)

print()


print(
    f"Male near-threshold points "
    f"[{NEAR_THRESHOLD_LOW}, "
    f"{NEAR_THRESHOLD_HIGH}]: "
    f"{len(male_near)}"
)


print(
    f"Female near-threshold points "
    f"[{NEAR_THRESHOLD_LOW}, "
    f"{NEAR_THRESHOLD_HIGH}]: "
    f"{len(female_near)}"
)


# ============================================================
# EXTRACT LOGISTIC REGRESSION COEFFICIENTS
# ============================================================

fitted_preprocessor = (
    model.named_steps[
        "preprocessor"
    ]
)


feature_names = (
    fitted_preprocessor
    .get_feature_names_out()
)


coefficients = (
    model.named_steps[
        "classifier"
    ]
    .coef_[0]
)


coefficient_df = pd.DataFrame({
    "Feature": feature_names,
    "Coefficient": coefficients
})


coefficient_df = (
    coefficient_df
    .sort_values(
        by="Coefficient",
        ascending=False
    )
)


coefficient_df.to_csv(
    COEFFICIENTS_CSV_PATH,
    index=False
)


# ============================================================
# PRINT COEFFICIENTS
# ============================================================

print()

print("=" * 70)
print("MODEL COEFFICIENTS")
print("=" * 70)


print(
    coefficient_df
    .to_string(
        index=False
    )
)


# ============================================================
# PLOT PREDICTED PROBABILITIES BY GENDER
#
# Gender is shown ONLY for fairness analysis.
# ============================================================

plot_df = results.copy()


rng_plot = np.random.default_rng(
    RANDOM_SEED
)


x_map = {
    "Male": 0,
    "Female": 1
}


plot_df["x"] = (
    plot_df["Gender"]
    .map(x_map)
)


plot_df["x_jitter"] = (
    plot_df["x"]
    + rng_plot.uniform(
        -0.08,
        0.08,
        len(plot_df)
    )
)


accepted = plot_df[
    plot_df[
        "Predicted_Admission"
    ] == 1
]


unaccepted = plot_df[
    plot_df[
        "Predicted_Admission"
    ] == 0
]


plt.figure(
    figsize=(7, 7)
)


# ------------------------------------------------------------
# Unaccepted
# ------------------------------------------------------------

plt.scatter(
    unaccepted["x_jitter"],
    unaccepted[
        "Predicted_Probability"
    ],
    color="red",
    s=45,
    alpha=0.65,
    label="Unaccepted"
)


# ------------------------------------------------------------
# Accepted
# ------------------------------------------------------------

plt.scatter(
    accepted["x_jitter"],
    accepted[
        "Predicted_Probability"
    ],
    color="blue",
    s=45,
    alpha=0.65,
    label="Accepted"
)


# ------------------------------------------------------------
# Classification threshold
# ------------------------------------------------------------

plt.axhline(
    y=THRESHOLD,
    color="black",
    linestyle="--",
    linewidth=1.5,
    label=f"Threshold = {THRESHOLD}"
)


# ------------------------------------------------------------
# Near-threshold region
# ------------------------------------------------------------

plt.axhspan(
    NEAR_THRESHOLD_LOW,
    NEAR_THRESHOLD_HIGH,
    alpha=0.08
)


# ------------------------------------------------------------
# Axes
# ------------------------------------------------------------

plt.xticks(
    [0, 1],
    [
        "Male",
        "Female"
    ]
)


plt.yticks(
    np.arange(
        0,
        1.1,
        0.1
    )
)


plt.ylim(
    0,
    1
)


plt.xlim(
    -0.3,
    1.3
)


plt.xlabel(
    "Gender"
)


plt.ylabel(
    "Predicted Admission Probability"
)


plt.title(
    "Unaware Logistic Regression\n"
    "Gender + Proxies Removed"
)


plt.grid(
    axis="y",
    linestyle=":",
    alpha=0.3
)


plt.legend()


plt.tight_layout()


plt.savefig(
    PLOT_PNG_PATH,
    dpi=300,
    bbox_inches="tight"
)


plt.show()


# ============================================================
# FINAL OUTPUT
# ============================================================

print()

print("=" * 70)
print("FILES CREATED")
print("=" * 70)


print(
    f"Original data:       "
    f"{DATA_CSV_PATH}"
)


print(
    f"Predictions:         "
    f"{PREDICTIONS_CSV_PATH}"
)


print(
    f"Coefficients:        "
    f"{COEFFICIENTS_CSV_PATH}"
)


print(
    f"Probability plot:    "
    f"{PLOT_PNG_PATH}"
)